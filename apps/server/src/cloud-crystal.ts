import { createHash, createHmac, timingSafeEqual } from "node:crypto";
import { JsonStore } from "./store.ts";
import type { StructuredLogger } from "./logger.ts";
import { parseCrystalIngest } from "../../../modules/pokemon-crystal/src/cloud-contracts.ts";
import type { Relay } from "./realtime.ts";
import reader from "../../../scripts/mgba-crystal.lua" with { type: "text" };
import transport from "../../../modules/pokemon-crystal/src/cloud-transport.lua" with { type: "text" };

type Source = { hash: string };
type Lease = { hash: string; session: string; sequence: number; expiresAt: number; nextAt: number };
const hash = (secret: string) => createHash("sha256").update(secret).digest("hex");
export function crystalIngestOrigin(origin: string) {
  const url = new URL(origin);
  if (
    url.protocol !== "http:" ||
    url.username ||
    url.password ||
    url.pathname !== "/" ||
    url.search ||
    url.hash ||
    !/^[A-Za-z0-9.-]+$/.test(url.hostname)
  )
    throw new Error(
      "POKEMON_INGEST_ORIGIN must be a plain HTTP origin without credentials or a path",
    );
  return url;
}
export function crystalScript(url: URL, session: string) {
  // Inputs are generated by the server, never arbitrary Lua or user-supplied hosts.
  const quote = (text: string) => JSON.stringify(text);
  return `-- Private Crystal mGBA source. Keep this file private; regenerate it to revoke older copies.\nlocal ingestHost = ${quote(url.hostname)}\nlocal ingestPort = ${Number(url.port || 80)}\nlocal ingestHostHeader = ${quote(url.host)}\nlocal ingestPath = ${quote(url.pathname + url.search)}\nlocal ingestSession = ${quote(session)} .. "-" .. tostring({}):gsub("[^A-Za-z0-9]", "")\n${transport}\n${reader.slice(0, reader.indexOf("local function atomicWrite"))}\nlocal lastSignature = nil\nlocal readerStatus = nil\nlocal frames = 0\nlocal lastPublish = 0\nlocal sequence = 0\ncallbacks:add("frame", function()\n  frames = frames + 1\n  if frames == 1 then console:log("Crystal cloud frame callback active") end\n  pumpHttp()\n  if frames % 30 ~= 0 then return end\n  if not supportedRom() then\n    if readerStatus ~= "rom" then console:error("Crystal cloud reader rejected the active ROM") end\n    readerStatus = "rom"; return\n  end\n  local team, badges = snapshot()\n  if not team then\n    if readerStatus ~= "snapshot" then console:warn("Crystal cloud snapshot unavailable: " .. tostring(badges)) end\n    readerStatus = "snapshot"; return\n  end\n  if readerStatus ~= "ready" then console:log("Crystal cloud snapshot ready; connecting to relay") end\n  readerStatus = "ready"\n  local signature = team .. badges\n  local now = os.time()\n  if signature == lastSignature and now - lastPublish < 2 then return end\n  if not httpReady() then return end\n  sequence = sequence + 1\n  local body = '{"version":1,"session":' .. quote(ingestSession) .. ',"sequence":' .. sequence .. ',"team":' .. team .. ',"badges":' .. badges .. '}'\n  if sendHttp(body) then lastSignature = signature; lastPublish = now end\nend)\nconsole:log("Crystal cloud reader loaded; checking live memory on the next frame")\n`;
}
/** Stores credentials and source-control metadata only. Never retains game snapshots. */
export class CloudCrystal {
  private sources: JsonStore<Source>;
  private leases = new Map<string, Lease>();
  constructor(
    directory: string,
    private origin: URL,
    private relay: Relay,
    private logger: StructuredLogger,
    private now = Date.now,
  ) {
    this.sources = new JsonStore(directory, "crystal-source");
  }
  async download(did: string, requestId: string) {
    const secret = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("hex");
    await this.sources.set(did, { hash: hash(secret) });
    this.leases.delete(did);
    const url = new URL(
      `/api/accounts/${encodeURIComponent(did)}/pokemon-crystal-mgba/ingest`,
      this.origin,
    );
    url.searchParams.set("token", secret);
    this.logger.log("info", "cloud.crystal.source-created", { requestId, did });
    return crystalScript(url, crypto.randomUUID());
  }
  async revoke(did: string, requestId: string) {
    await this.sources.del(did);
    this.leases.delete(did);
    this.logger.log("info", "cloud.crystal.source-revoked", { requestId, did });
  }
  async authorize(did: string, secret: unknown) {
    if (typeof secret !== "string" || !/^[a-f0-9]{64}$/.test(secret)) return;
    const source = await this.sources.get(did);
    const actual = hash(secret);
    if (source && timingSafeEqual(Buffer.from(source.hash), Buffer.from(actual))) return actual;
  }
  /** Short-lived signed party witness. No party data is retained on the server. */
  private petWitness(did: string, sourceHash: string, party: { id: string; name: string }[]) {
    const payload = Buffer.from(
      JSON.stringify({
        did,
        until: this.now() + 15000,
        party: party.map(({ id, name }) => ({ id, name })),
      }),
    ).toString("base64url");
    return `${payload}.${createHmac("sha256", sourceHash).update(payload).digest("base64url")}`;
  }
  async petTarget(did: string, witness: unknown, name?: string) {
    if (typeof witness !== "string" || witness.length > 4096)
      throw new Error("Invalid live party witness");
    const [payload, signature, extra] = witness.split(".");
    const source = await this.sources.get(did);
    if (!source || !payload || !signature || extra) throw new Error("Invalid live party witness");
    const expected = createHmac("sha256", source.hash).update(payload).digest();
    const actual = Buffer.from(signature, "base64url");
    if (actual.length !== expected.length || !timingSafeEqual(expected, actual))
      throw new Error("Invalid live party witness");
    const value = JSON.parse(Buffer.from(payload, "base64url").toString());
    if (value.did !== did || value.until < this.now())
      throw new Error("Live party witness expired");
    if (name === undefined) return;
    const member = value.party.find(
      (p: { name: string }) => p.name.trim().toLowerCase() === name.trim().toLowerCase(),
    );
    if (!member) throw new Error("Pokémon is not in the live party");
    return member.id as string;
  }
  /** Rate/source metadata only; synchronous validation and broadcast release the payload immediately. */
  relaySnapshot(did: string, sourceHash: string, body: unknown, requestId: string) {
    this.cleanup();
    const now = this.now();
    const previous = this.leases.get(did);
    if (previous?.nextAt && previous.nextAt > now) return { status: 429, reason: "rate-limit" };
    if (!previous && this.leases.size >= 10000) return { status: 503, reason: "capacity" };
    const parsed = parseCrystalIngest(body);
    if (previous && previous.hash === sourceHash && previous.expiresAt > now) {
      if (previous.session !== parsed.session)
        return { status: 409, reason: "another-source-active" };
      if (parsed.sequence <= previous.sequence) return { status: 409, reason: "stale-sequence" };
    }
    this.leases.set(did, {
      hash: sourceHash,
      session: parsed.session,
      sequence: parsed.sequence,
      expiresAt: now + 15000,
      nextAt: now + 100,
    });
    const delivered = this.relay.crystal(
      did,
      parsed.snapshot,
      this.petWitness(did, sourceHash, parsed.snapshot.party),
    );
    if (!previous || previous.hash !== sourceHash || previous.expiresAt <= now)
      this.logger.log("info", "cloud.crystal.source-active", { requestId, did, delivered });
    return { status: 200, delivered };
  }
  cleanup() {
    for (const [did, lease] of this.leases)
      if (lease.expiresAt <= this.now()) this.leases.delete(did);
  }
}
